/** Точки блока с координатами, пересчитанными в проценты вырезки. */
export function mobileBlockNodes(
  block: MontazhMobileBlock,
  nodes: MontazhNode[],
): MontazhNode[] {
  return block.nodes
    .map((n) => nodes.find((node) => node.n === n))
    .filter((node): node is MontazhNode => Boolean(node))
    .map((node) => ({
      ...node,
      x: ((node.x / 100) * SRC_W - block.left) / BLOCK_W * 100,
    }));
}

