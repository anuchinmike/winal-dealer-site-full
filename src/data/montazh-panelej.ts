export const montazhNodes: MontazhNode[] = content.map((c) => {
  const p = montazhPoints.find((pt) => pt.n === c.n);
  if (!p) throw new Error(`Нет координат для узла ${c.n}`);
  const profiles = Array.from(new Set(c.solutions.flatMap((s) => s.profiles)));
  return {
    ...c,
    text: c.solutions[0].text,
    profiles,
    images: c.solutions.flatMap((s) => s.images),
    x: p.x,
    y: p.y,
    depth: p.depth,
  };
});

